# imports --------------------------------------------------------------
# -- computations
import numpy as np

# -- text processing
import re

# -- I/O operations
import os


# constants ------------------------------------------------------------
# a signed float as the solver writes it into the body dictionaries
FLOAT_PATTERN = r"-?\ *[0-9]+\.?[0-9]*(?:[Ee]\ *[-+]?\ *[0-9]+)?"


# auxiliary functions --------------------------------------------------


def can_be_converted_to_float(value):
    """
        tell whether a text can be read as a number

        value ... the text to test
    """
    try:
        float(value)
        return True
    except ValueError:
        return False


def get_particles_list(case_dir):
    """
        return the particle numbers carried by the .info files of a folder

        case_dir ... folder holding the body<id>.info files
    """
    directory = case_dir
    strings = list(set([name for name in os.listdir(directory)]))
    full_list = []
    for i in range(len(strings)):
        if strings[i][-5:] == '.info':
            stem = strings[i][:-5]
            full_list.append(stem[4:])
    if len(full_list) > 0:
        full_list.sort(key=float)
    return full_list


# auxiliary classes ----------------------------------------------------


class VTKFile:
    """
        one ASCII POLYDATA file holding the point fields of one time level

        output_path ... file the polydata is written into
        n_particles ... number of points announced by the file, lowered
                        while reading for the bodies that are no spheres
        particles ... the SphereBody objects to write out
    """

    def __init__(self, output_path):
        """
            start empty, with no particles recorded yet
        """
        self.output_path = output_path
        self.n_particles = 0
        self.particles = []

    def write_file_head(self):
        """
            write the polydata header, which truncates any old file
        """
        with open(self.output_path, 'w') as file:
            file.write("# vtk DataFile Version 4.2\n")
            file.write("Generated by HFDIBDEM-Python\n")
            file.write("ASCII\n")
            file.write("DATASET POLYDATA\n")

    def write_file_points(self):
        """
            write the point coordinates, three points to a line
        """
        with open(self.output_path, 'a') as file:
            file.write("\nPOINTS " + str(self.n_particles) + " float\n")
            k = 0
            for particle in self.particles:
                file.write(str(particle.pos[0]) + " " + str(particle.pos[1]) +
                           " " + str(particle.pos[2]) + " ")
                k += 1
                if k == 3:
                    file.write("\n")
                    k = 0
            if k != 0:
                file.write("\n")

    def write_vertices(self):
        """
            write the vertex list, one vertex per point
        """
        with open(self.output_path, 'a') as file:
            file.write("\nVERTICES " + str(self.n_particles) + " " +
                       str(self.n_particles * 2) + "\n")
            for i in range(self.n_particles):
                file.write("1 " + str(i) + "\n")

    def write_point_data_head(self, n_sets=5):
        """
            open the point data block that holds n_sets fields
        """
        with open(self.output_path, 'a') as file:
            file.write("\nPOINT_DATA " + str(self.n_particles) + "\n")
            file.write("FIELD FieldData " + str(n_sets) + "\n")

    def write_id_data(self):
        """
            write the id field, nine values to a line
        """
        with open(self.output_path, 'a') as file:
            file.write("id 1 " + str(self.n_particles) + " int\n")
            k = 0
            for i in range(self.n_particles):
                file.write(str(self.particles[i].body_id) + " ")
                k += 1
                if k == 9:
                    file.write("\n")
                    k = 0
            if k != 0:
                file.write("\n")

    def write_static_data(self):
        """
            write the static flag as an integer, nine values to a line
        """
        with open(self.output_path, 'a') as file:
            file.write("static 1 " + str(self.n_particles) + " int\n")
            k = 0
            for i in range(self.n_particles):
                file.write(str(int(self.particles[i].static)) + " ")
                k += 1
                if k == 9:
                    file.write("\n")
                    k = 0
            if k != 0:
                file.write("\n")

    def write_radius_data(self):
        """
            write the radius field, nine values to a line
        """
        with open(self.output_path, 'a') as file:
            file.write("r 1 " + str(self.n_particles) + " float\n")
            k = 0
            for i in range(self.n_particles):
                file.write(str(self.particles[i].r) + " ")
                k += 1
                if k == 9:
                    file.write("\n")
                    k = 0
            if k != 0:
                file.write("\n")

    def write_lin_vel_data(self):
        """
            write the linear velocity field, one vector to a line
        """
        with open(self.output_path, 'a') as file:
            file.write("v 3 " + str(self.n_particles) + " float\n")
            k = 0
            for i in range(self.n_particles):
                file.write(str(self.particles[i].lin_vel[0]) + " " +
                           str(self.particles[i].lin_vel[1]) + " " +
                           str(self.particles[i].lin_vel[2]) + " ")
                k += 1
                if k == 3:
                    file.write("\n")
                    k = 0
            if k != 0:
                file.write("\n")

    def write_omega_data(self):
        """
            write the angular velocity field, nine values to a line
        """
        with open(self.output_path, 'a') as file:
            file.write("omega 1 " + str(self.n_particles) + " float\n")
            k = 0
            for i in range(self.n_particles):
                file.write(str(self.particles[i].omega) + " ")
                k += 1
                if k == 9:
                    file.write("\n")
                    k = 0
            if k != 0:
                file.write("\n")

    def write_file(self):
        """
            write the whole file, head first and then every field
        """
        self.write_file_head()
        self.write_file_points()
        self.write_vertices()
        self.write_point_data_head(5)
        self.write_id_data()
        self.write_static_data()
        self.write_radius_data()
        self.write_lin_vel_data()
        self.write_omega_data()


class SphereBody:
    """
        the state of one spherical body, as read from its .info file

        body_id ... number the solver gave the body
        name ... body type name taken from the dictionary
        pos ... centre of the body
        lin_vel ... linear velocity of the body
        omega ... angular velocity of the body
        r ... radius of the body
        static ... whether the body is held fixed
    """

    def __init__(self):
        """
            start at the origin, at rest and not held fixed
        """
        self.body_id = 0
        self.name = "sphere"
        self.pos = np.zeros(3)
        self.lin_vel = np.zeros(3)
        self.omega = 0
        self.r = 0
        self.static = False

    def print_stats(self):
        """
            print the state of the body, for debugging purposes
        """
        print("ID: ", self.body_id)
        print("Name: ", self.name)
        print("Position: ", self.pos)
        print("Linear Velocity: ", self.lin_vel)
        print("Angular Velocity: ", self.omega)
        print("Radius: ", self.r)
        print("Static: ", self.static)


# auxiliary functions --------------------------------------------------


def read_body_info(path):
    """
        read one body<id>.info dictionary into a SphereBody

        path ... the dictionary to read
    """
    id_strings = [
        "bodyId",
        "bodyName        ",
        "Vel",
        "omega",
        "static",
        "    position",
        "    radius",
    ]

    body = SphereBody()

    with open(path, 'r') as file:
        data = file.readlines()
    for line in data:
        for string in id_strings:
            first_index = line.find(string)
            if first_index == 0 and string == "bodyId":
                values = [float(str_to_val) for str_to_val in
                          re.findall(FLOAT_PATTERN, line[len(string):])]
                body.body_id = int(values[0])
            elif first_index == 0 and string == "bodyName        ":
                body.name = str(line[len(string):-2])
            elif first_index == 0 and string == "Vel":
                vec = [float(str_to_val) for str_to_val in
                       re.findall(FLOAT_PATTERN, line[len(string):])]
                body.lin_vel = np.array(vec)
            elif first_index == 0 and string == "omega":
                values = [float(str_to_val) for str_to_val in
                          re.findall(FLOAT_PATTERN, line[len(string):])]
                body.omega = values[0]
            elif first_index == 0 and string == "static":
                values = [float(str_to_val) for str_to_val in
                          re.findall(FLOAT_PATTERN, line[len(string):])]
                body.static = bool(values[0])
            elif first_index == 0 and string == "    position":
                vec = [float(str_to_val) for str_to_val in
                       re.findall(FLOAT_PATTERN, line[len(string):])]
                body.pos = np.array(vec)
            elif first_index == 0 and string == "    radius":
                values = [float(str_to_val) for str_to_val in
                          re.findall(FLOAT_PATTERN, line[len(string):])]
                body.r = values[0]

            if first_index == 0:
                id_strings.pop(id_strings.index(string))
    return body


def is_sphere_body_info(path):
    """
        tell whether a dictionary describes a sphere body

        path ... the dictionary to look into
    """
    with open(path, 'r') as file:
        data = file.readlines()
    for line in data:
        if line.find("sphere") == 0:
            return True
    return False


# main -----------------------------------------------------------------


def main():
    """
        convert every time level found in bodiesInfo/ into one polydata
        file in VTKReconstruct/, reading only the spherical bodies

        n_present ... number of already converted time levels, set it to
                      resume an interrupted conversion
    """
    # EDITABLE -- number of time levels already converted
    n_present = 0
    time_level_list = os.listdir('bodiesInfo/')
    for item in time_level_list:
        if can_be_converted_to_float(item):
            index = time_level_list.index(item)
            if float(item) == int(float(item)):
                time_level_list[index] = int(float(item))
            else:
                time_level_list[index] = float(item)
    time_level_list.sort(key=float)

    simulation_length = len(os.listdir('bodiesInfo/'))
    if not os.path.isdir('VTKReconstruct/'):
        os.system('mkdir VTKReconstruct/')
    else:
        n_present = len(os.listdir('VTKReconstruct/'))
        print(" -- Warning: VTKReconstruct/ already exists. The program will"
              " append the data to the existing files size: ", n_present)
    print(" -- Time level outputs to process: ", time_level_list[n_present:])
    print(" -- Simulation length: ", simulation_length)

    for t in time_level_list[n_present:]:
        i = time_level_list.index(t)
        path = "bodiesInfo/" + str(t) + "/"
        print("-- Reading: ", path)
        particle_number_list = get_particles_list(path)
        file_name = "VTKReconstruct/ParticleData." + str(i).zfill(4) + ".vtk"

        vtk_file = VTKFile(file_name)
        vtk_file.n_particles = len(particle_number_list)
        for particle in particle_number_list:
            if is_sphere_body_info(path + "body" + str(particle) + ".info"):
                body = read_body_info(path + "body" + str(particle) + ".info")
                vtk_file.particles.append(body)
            else:
                vtk_file.n_particles -= 1
        vtk_file.write_file()


# launcher -------------------------------------------------------------
if __name__ == "__main__":
    main()
